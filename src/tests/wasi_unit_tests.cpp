struct WasiTestCase {
  const char *Name;
  const uint8_t *WasmData;
  size_t WasmSize;
  int ExpectedExitCode;
};

// Run a WASM module with the WASI host module loaded and verify the exit code.
static void runWasiTest(const WasiTestCase &TC) {
  RuntimeConfig Config;
  std::unique_ptr<Runtime> RT = Runtime::newRuntime(Config);
  ASSERT_NE(RT, nullptr) << "failed to create runtime for " << TC.Name;

  HostModule *WASIMod = LOAD_HOST_MODULE(RT, zen::host, wasi_snapshot_preview1);
  ASSERT_NE(WASIMod, nullptr)
      << "failed to load WASI host module for " << TC.Name;

  MayBe<Module *> ModRet = RT->loadModule(TC.Name, TC.WasmData, TC.WasmSize);
  ASSERT_TRUE(ModRet) << "failed to load module " << TC.Name << ": "
                      << ModRet.getError().getFormattedMessage();
  Module *Mod = *ModRet;

  Isolation *Iso = RT->createManagedIsolation();
  ASSERT_NE(Iso, nullptr) << "failed to create isolation for " << TC.Name;

  MayBe<Instance *> InstRet = Iso->createInstance(*Mod);
  ASSERT_TRUE(InstRet) << "failed to create instance for " << TC.Name << ": "
                       << InstRet.getError().getFormattedMessage();
  Instance *Inst = *InstRet;

  std::vector<TypedValue> Results;
  RT->callWasmMain(*Inst, Results);

  // proc_exit clears the InstanceExit error and stores the exit code.
  EXPECT_EQ(Inst->getExitCode(), TC.ExpectedExitCode)
      << "unexpected exit code for test " << TC.Name;
}

